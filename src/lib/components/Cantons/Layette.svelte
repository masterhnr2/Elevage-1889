<p> Le gilet comme les sabots en photographie sont des habits de costume traditionnel mais ils permettent de visionner ce que pouvait donner les vêtements d'époque. Ils sont donc plutôt portés le dimanche et les jours de fêtes. Le gilet est en drap de laine noir doublé d'une toile de lin. Il possède une double rangée de boutons dorés en métal. Les boutonnières sont en fils de coton vert, de même pour les deux poches. L'arrière du gilet est quant à lui marron. Les sabots sont aussi de couleur noire avec la partie avant pointue et recourbée. Les semelles et talons ont été renforcés avec des clous. Un clou maintient un fil sur le dessus du pied.  </p> 


<h1> Les vêtures des enfants à Lesneven, Plabennec et Ouessant: l'avènement du costume breton par ville </h1>
<p> Cantons au Nord de Brest, les villes de Lesneven et Plabennec ainsi que l'île de Ouessant n'ont pas les mêmes traditions en terme de vêtures avant 1860. Par "vêtures", on entend les vêtements des enfants après environ 6 ans. L'enfance est peu particularisé dans les vêtements. En général, les vêtements sont des versions miniatures des adultes. </p> 
<hr />
<h2> Avant l'enquête de Bérard, déjà une distinction entre ville et campagne </h2> 
<p> La ville de Lesneven avait un uniforme pour les hommes et les garçons habitant de la ville. Cet uniforme était composé d' "un pantalon gris, une veste bleue". Pour ceux qui habitent en campagne, il s'agit d' "un pantalon de drap large serré aux jarrets" et "une veste très courte". Les dimanches et les jours de fête, tous portaient des chapeaux en feutre, des galoches (des chaussures avec des semelles en bois) ou des souliers. Les jours de travail, ils étaient chaussés de sabots clos. </p>
<br>
<p> La ville de Plabennec diffère de Lesneven. Les petits garçons portaient le costume en usage dans tous le Léon: un gilet et un paletot noirs. Ils avaient aussi un chapeau de feutre à larges bords presque semblable à celui des ecclésiastiques. Les petites filles étaient vêtues de "jupes de drap noir sur un jupon de molleton bleu, un petit châle de couleur et des bonnets de linge en forme de serre-tête". Rares étaient les variations sur les vêtures. </p> 
<br>
<p> L'île de Ouessant avait un costume différent. Les petits garçons avaient des costumes inspirés des matelots. Ils portaient une casquette et remplaçaient la tunique par une blouse en grosse laine bleue et un jersey bleu ou noir. Les filles portaient un costume constitué d'un linge en jupe et jupon de gros draps ou de gros coton. En hiver comme en été, ils mettaient des gros sabots clos de hêtre fermé. La particularité de l'île venait des enfants qui portaient des bretelles, peu importe le sexe, jusqu'à leur dix ans. Les garçons de moins de 8 ans environ avaient des robes. </p>


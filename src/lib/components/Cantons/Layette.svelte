<h2> Au coeur de l'enquête : un costume changeant dans le temps et l'espace</h2> 
<p> Lors de l'enquête, le costume n'a pas changé dans les trois villes. Il faut cependant dans l'ouvrage se référer à Brest pour certains détails. Les bretelles, spécificité de Ouessant, étaient conservées. Bérard note également qu'à Ouessant "les garçons portent la culotte maintenant dès l'âge de 4 ans." Si les jours de la semaine, la vêture des filles ne changeait pas énormément, un coiffe de couleur, "un châle de laine ou de coton, un tablier, une jupe et un corsage de laine". Les jours de fêtes et dimanches, la couleur de la coiffe devenait blanche et était accompagnée d'un serre-tête noir. </p>

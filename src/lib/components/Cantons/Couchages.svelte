<br>

<p>Le choix de la literie suivait ce même principe de faconnage avec une superposition de couches pour former
un cocon chaud a l'enfant. Elle se composait essentiellement d'une couette ou d'une paillasse de balle d'avoine,
le tout complété par des draps en toile de chanvre, des couvertures, un couvre-pied, un oreiller et parfois des
rideaux. Selon l'aisance de la famille, la couette ou la paillasse pouvait être posée directement sur le berceau ou
sur un lit de paille surélevé pour renforcer l'isolation, le tout étant régulièrement aéré et renouvelé plusieurs fois
dans l'année.
Quant à l'emplacement du berceau, il répondait généralement à un souci de proximité entre l'enfant et les
parents. Le berceau était alors installé près du lit parental sur un banc appelé <em>banc-dossier</em>. Mais, il
était également habituel que l'enfant soit couché dans une autre pièce selon l'aisance financière de la famille,
l'âge ou la présence d'une nourrice .</p><br>

<p> Par ailleurs, l'enquête identifie d'autres moyens de couchage liés aux contraintes des familles ayant d'autres
enfants de bas-âge ou des difficultés financières. Dans ces cas-là, la solution courante venait soit de l'emploi
d'un grand berceau pour les deux enfants, soit de l'aide d'un voisin qui <em>pouvait reléguer un berceau</em> à
la mère. Dans d'autres cantons, il s'agissait néanmoins d'utiliser des mobiliers destinés à d'autres fins comme
des alternatives de couchage pour les enfants. C'est l'exemple typique de Huelgoat : le fond d'une armoire
servait en ce sens de couchage d'appoint, ou l'on installait l'un des enfants (le plus souvent l'aîné) avec la même
literie rudimentaire .</p><br>

<p> Au-delà de ces dispositions matérielles, le bercement s'imposait comme l'une des pratiques de médiation les
plus employées autrefois pour apaiser les enfants. Dans tous les cantons, le bercement était souvent utilisé pour
calmer et endormir les enfants. Le bercement a la ficelle integrée au berceau était l'une des méthodes utilisée
à Le Faou pour permettre à la nourrice de calmer l'enfant. Selon les croyances de l'époque, il constituait à ce titre
une prévention contre l'apparition des hernies abdominales causées par les crises de pleurs. Le bercement était
également une alternative aux méthodes de <em>gavage au lait de vache</em> pour produire un effet sédatif
similaire chez les enfants. Comme le relève l'auteur, la pratique du bercement était paradoxalement décriée
<em>à tort</em> par les hygiénistes comme nocive alors qu'elle <em>n'altérait pas la santé des enfants</em>
et répondait aux besoins de la vie domestique. </p><br>

<h2>Aujourd'hui</h2>
<br>
<p> L'évolution des modes de couchage n'était pas tout à fait uniforme dans tous les cantons. Au sein d'un
même canton, la modernité des couchages restait partielle. Les villes adoptaient de nouvelles modes de
couchage, mais certaines campagnes employaient encore des procédés anciens. À Huelgoat par exemple,
l'usage des armoires comme lits restait courant pour les jeunes enfants. Le <em> lit clos</em> était également
l'un des mobiliers les plus emblématiques pour le couchage des enfants : il s'agissait d'un meuble imposant
faisant office de lit aux parents avec un ou deux couchages superposés ; la partie supérieure était réservée aux
enfants et la partie inférieure aux parents. Parfois, le lit clos intégrait directement un <em>kavel</em>, berceau
de la forme d'un demi cylindre renversé destiné aux nouveau-nés. Cette proximité étroite explique les critiques
de l'auteur qui y voit une pratique <em>«&nbspanti hygiénique puisqu'[elle] oblige l'enfant a dormir dans une
atmosphère constamment viciée par suite du peu d'espace existant dans le lit des parents&nbsp» .</em></p> <br>


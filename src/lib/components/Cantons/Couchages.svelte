<p> Même si le lit clos et d'anciens modes de couchages persistent encore, les habitudes évoluent d'un canton à
l'autre. Le changement des berceaux se manifeste par l'apparition de modèles plus grands et plus légers en
osier ou en bois sculpté (chêne ou châtaignier) portant des dessins ou des ornements. La tradition reste
néanmoins ancrée dans le choix et l'organisation de la literie : l'usage de la literie rudimentaire et du banc pour y
poser le berceau est toujours courant dans plusieurs cantons. À Crozon ou Pleyben, l'auteur note l'emploi des
nouveaux berceaux avec des couchages plus chauds et confortables (matelas d'édredon, couverture en laine),
et l'usage s'étend jusqu'à l'âge de 2 ou 3 ans. Malgré les évolutions des couchages, certaines coutumes
subsistent encore comme le partage du même berceau pour les jumeaux, même si sa taille n'assumait pas la
croissance des enfants .</p>

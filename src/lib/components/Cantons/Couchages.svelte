<h1>Les modes de couchage : Pleyben, Crozon, Le Faou</h1>

<p>Les <em> modes de couchage</em> correspondent à l'ensemble des dispositions matérielles et
symboliques mises en place pour assurer le sommeil des enfants. Ce dispositif constitue tout un
<em>savoir-faire</em> qui articule le contenant (le berceau, la bercelonnette, le lit clos, etc.), les textures
(la paillasse, le drap, les couettes), l'emplacement et les pratiques qui l'entourent comme le bercement, le
chant ou l'emmaillotement. Huelgoat, Crozon, Pleyben, et Le Faou présentent dans l'enquête d'Émile
Bérard des similarités et quelquefois des particularités qui peuvent apparaître dans d'autres cantons,
mais illustrent de façon générale l'évolution des modes de couchage dans l'ensemble du Finistère au
XIX<sup>ème</sup> siècle.</p><br>

<h2>Autrefois</h2>
<br>
<p> Bien que la forme et le matériau puissent varier selon les cantons, l'usage des berceaux était
généralement courant dans tout le Finistère. À Pleyben et Le Faou, le couchage était presque identique :
<em>une caisse rustique ou une boîte massive en bois de chêne [ ... ] ou de châtaignier reposant sur des
supports en forme d'arc de cercle</em>. À la différence de Huelgoat, l'auteur note l'usage de paniers en
osier avec un mécanisme de fermeture permettant de protéger l'enfant des piqûres d'insectes et des
animaux de la ferme. Le seul point commun entre ces berceaux d'autrefois résidait dans leur petitesse
extrême qui s'expliquait par le port du maillot. Cette pratique courante était soutenue par les adultes qui
pensaient que les corps des nouveaux-nés étaient inarticulés ou inachevés et nécessitaient à nouveau un
faconnage. À Crozon par exemple, l'usage était d'employer des berceaux en forme de bateaux de très
petites dimensions ou des berceaux légers nommés <em>brancelles</em>, suspendus à l'intérieur même
du lit clos des parents. </p> <br>

